import { ChangeDetectionStrategy, Component } from '@angular/core';
import { RouterLink } from '@angular/router';
import { guideFor } from '../../core/config/tools';
import { formatDate, formatPeso, formatPercent } from '../../shared/format';
import { PageHeaderComponent } from '../../shared/ui/page-header.component';
import { RelatedComponent } from '../../shared/ui/related.component';
import { computeAmortization, round2 } from '../../shared/utils/ph-calculators.util';
import { PH_RULES } from '../../shared/utils/ph-rules';

// The annual diminishing-balance rate that gives the same monthly payment as an add-on rate.
function equivalentRate(amount: number, payment: number, months: number): number {
  let lo = 0;
  let hi = 100;
  for (let i = 0; i < 60; i++) {
    const mid = (lo + hi) / 2;
    if (computeAmortization(amount, mid, months).payment < payment) lo = mid;
    else hi = mid;
  }
  return round2((lo + hi) / 2);
}

@Component({
  selector: 'app-article-loan-amortization-ph',
  imports: [RouterLink, PageHeaderComponent, RelatedComponent],
  changeDetection: ChangeDetectionStrategy.OnPush,
  templateUrl: './loan-amortization-ph.component.html',
})
export class LoanAmortizationPhArticleComponent {
  readonly updated = formatDate(guideFor('/articles/loan-amortization-ph')!.updated);

  // Worked example: a Pag-IBIG housing loan on the 3-year repricing rate, generated by the calculator engine.
  readonly example = (() => {
    const amount = 1_000_000;
    const years = 20;
    const rate = PH_RULES.housingLoan.ratesByRepricingYears[3];
    const months = years * 12;
    const { payment, schedule } = computeAmortization(amount, rate, months);
    const totalPaid = round2(payment * months);
    const row = (r: (typeof schedule)[number]) => ({
      period: r.period,
      interest: formatPeso(r.interest),
      principal: formatPeso(r.principal),
      balance: formatPeso(r.balance),
    });
    return {
      amount: formatPeso(amount, 0),
      years,
      months,
      rate: formatPercent(rate),
      monthlyRate: formatPercent(rate / 12, 4),
      payment: formatPeso(payment),
      totalPaid: formatPeso(totalPaid),
      totalInterest: formatPeso(totalPaid - amount),
      firstInterest: formatPeso(schedule[0].interest),
      rows: [...schedule.slice(0, 3), schedule[months - 1]].map(row),
    };
  })();

  // Add-on vs diminishing balance: same quoted rate, very different cost.
  readonly addOn = (() => {
    const amount = 300_000;
    const years = 3;
    const ratePct = 10;
    const months = years * 12;
    const interest = amount * (ratePct / 100) * years;
    const payment = round2((amount + interest) / months);
    const diminishing = computeAmortization(amount, ratePct, months).payment;
    return {
      amount: formatPeso(amount, 0),
      years,
      months,
      rate: formatPercent(ratePct),
      interest: formatPeso(interest, 0),
      payment: formatPeso(payment),
      diminishingPayment: formatPeso(diminishing),
      diminishingInterest: formatPeso(round2(diminishing * months - amount)),
      equivalent: formatPercent(equivalentRate(amount, payment, months), 1),
    };
  })();
}
